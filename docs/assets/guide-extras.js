  var RX = GLOSSARY.map(function (g) { return new RegExp('(^|[^\\p{L}\\d])(' + g[0] + ')(?![\\p{L}\\d])', 'iu'); });
  function addGlossary(pbody) {
    if (pbody.querySelector('.gl')) return;
    var used = {};
    var walker = document.createTreeWalker(pbody, NodeFilter.SHOW_TEXT, {
      acceptNode: function (n) {
        var p = n.parentNode;
        if (!p || p.closest('pre,code,h1,.kicker,.kit-meta,.kit-oops,summary,table,button,a,.gl,#selBox')) return NodeFilter.FILTER_REJECT;
        return /\S/.test(n.nodeValue) ? NodeFilter.FILTER_ACCEPT : NodeFilter.FILTER_REJECT;
      }
    });
    var nodes = [], n;
    while ((n = walker.nextNode())) nodes.push(n);
    nodes.forEach(function (node) {
      for (var g = 0; g < GLOSSARY.length; g++) {
        if (used[g]) continue;
        var m = RX[g].exec(node.nodeValue);
        if (!m) continue;
        used[g] = true;
        var start = m.index + m[1].length, word = m[2];
        var after = node.splitText(start);
        after.nodeValue = after.nodeValue.slice(word.length);
        var span = document.createElement('span');
        span.className = 'gl'; span.tabIndex = 0; span.setAttribute('role', 'button');
        span.setAttribute('data-g', g); span.textContent = word;
        span.setAttribute('aria-label', word + ': ' + GLOSSARY[g][2]);
        after.parentNode.insertBefore(span, after);
        node = after;          // continue in the rest of this text
        g = -1;
      }
    });
  }

  var tip = null, tipFor = null;
  function showTip(el) {
    if (!tip) { tip = document.createElement('div'); tip.className = 'kit-tip'; tip.setAttribute('role', 'tooltip'); document.body.appendChild(tip); }
    var g = GLOSSARY[+el.getAttribute('data-g')];
    tip.innerHTML = '<b>' + esc(g[1]) + '</b>' + esc(g[2]);
    tip.hidden = false; tipFor = el;
    var r = el.getBoundingClientRect(), w = Math.min(300, innerWidth - 24);
    tip.style.width = w + 'px';
    var x = Math.max(12, Math.min(innerWidth - w - 12, r.left + r.width / 2 - w / 2));
    var y = r.bottom + 8;
    tip.style.left = x + 'px'; tip.style.top = y + 'px';
    var th = tip.getBoundingClientRect().height;
    if (y + th > innerHeight - 8) tip.style.top = Math.max(8, r.top - th - 8) + 'px';
  }
